#!/usr/bin/env bash
set -euo pipefail

if [[ "$(uname -s)" != Darwin ]]; then
  echo 'Run DMG packaging on macOS.' >&2
  exit 1
fi

archive="${1:?Pass the ZIP generated by package_macos_personal.sh}"
output_dir="$(dirname "$archive")"
archive_name="$(basename "$archive" .zip)"
app_name=lvpai_ftp_client.app
arch="$(uname -m)"
work="$(mktemp -d "${TMPDIR:-/tmp}/lvpai-macos-dmg.XXXXXX")"
mount="$work/mount"
mounted=false
cleanup() {
  if [[ "$mounted" == true ]]; then
    hdiutil detach "$mount" || return
  fi
  rm -rf "$work"
}
trap cleanup EXIT

ditto -x -k "$archive" "$work/archive"
app="$work/archive/$archive_name/$app_name"
info="$app/Contents/Info.plist"
version="$(plutil -extract CFBundleShortVersionString raw -o - "$info")"
build="$(plutil -extract CFBundleVersion raw -o - "$info")"
executable="$(plutil -extract CFBundleExecutable raw -o - "$info")"
display_name="$(plutil -extract CFBundleDisplayName raw -o - "$info")"
channel="$(plutil -extract LvpaiUpdateChannel raw -o - "$info")"
if [[ "$channel" != prd ]]; then
  app_name="$display_name.app"
fi
image="lvpai-ftp-$version-$build-macos-$arch-personal.dmg"

mkdir "$work/image" "$mount"
ditto "$app" "$work/image/$app_name"
ln -s /Applications "$work/image/Applications"
hdiutil create -volname "$display_name" -srcfolder "$work/image" \
  -format UDZO -fs HFS+ "$work/$image"
hdiutil verify "$work/$image"
hdiutil attach -readonly -nobrowse -mountpoint "$mount" "$work/$image"
mounted=true

test "$(readlink "$mount/Applications")" = /Applications
app="$mount/$app_name"
node="$app/Contents/Resources/print-runtime/node"
codesign --verify --deep --strict "$app"
codesign --verify --strict "$node"
lipo "$app/Contents/MacOS/$executable" -verify_arch "$arch"
lipo "$node" -verify_arch "$arch"
"$node" --version
hdiutil detach "$mount"
mounted=false

(cd "$work" && shasum -a 256 "$image") | tee "$work/$image.sha256"
mv "$work/$image" "$work/$image.sha256" "$output_dir/"

if [[ "$channel" == prd && "$arch" == arm64 ]]; then
  root="$(cd "$(dirname "$0")/.." && pwd)"
  python3 - "$root" "$output_dir/$image" "$version" "$build" <<'PY'
from pathlib import Path
import shutil
import sys

root, image, version, build = sys.argv[1:]
sys.path.insert(0, str(Path(root) / "tool"))
from package_release import write_release_info

out = Path(root) / "build/releases/prd/macos-arm64"
out.mkdir(parents=True, exist_ok=True)
package = out / f"lvpai-ftp-{version}-{build}-macos-arm64.dmg"
if package.exists():
    raise FileExistsError(package)
shutil.copyfile(image, package)
write_release_info(out / "release-info.json", package, version=version, code=build,
                   platform="macos-arm64", channel="prd")
PY
fi
